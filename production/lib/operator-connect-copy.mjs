// What each card is called in a sentence. Kept apart from the card titles so a
// banner can name a provider without repeating the card's own heading.
export const PROVIDER_DISPLAY_NAMES = Object.freeze({
  google: "Gmail",
  google_drive: "Google Drive",
  whatsapp: "WhatsApp",
  viber: "Viber",
  facebook: "Facebook",
  instagram: "Instagram",
  github: "GitHub",
  cloudflare: "Cloudflare",
  neon: "Neon",
  ai: { bg: "ИИ доставчикът", ru: "Провайдер ИИ", en: "The AI provider" },
});

export function providerDisplayName(provider, locale = "en") {
  const name = PROVIDER_DISPLAY_NAMES[String(provider || "")];
  if (!name) return String(provider || "");
  return typeof name === "string" ? name : name[locale] || name.en;
}

// Copy keys are derived from the provider id, so a card added to the catalogue
// without its three translations fails a test rather than rendering a raw key.
export function providerCopyKey(provider, suffix) {
  const camel = String(provider || "")
    .split("_")
    .map((part, index) => (index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join("");
  return `${camel === "ai" ? "aiProvider" : camel}${suffix}`;
}

export function operatorConnectCopy(locale) {
  return CONNECT_COPY[locale] || CONNECT_COPY.en;
}

